"""
Deep Architecture Benchmark Script
Tests the FULL PIPELINE (Rule-Based -> Web API) against 500 diverse scam scenarios
from the actual dataset.jsonl, with per-category breakdown.
"""
import asyncio
import json
import random
import time
import sys
import os

# Add the factcheck dir to path so we can import local_llm
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from local_llm import LocalScamClassifier

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# Load full dataset
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
DATASET_PATH = os.path.join(os.path.dirname(__file__), '..', 'ai_training', 'dataset.jsonl')

def load_dataset(path, max_samples=500):
    samples = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            data = json.loads(line)
            transcript = data.get('input', '')
            output_raw = data.get('output', '{}')
            if isinstance(output_raw, str):
                output = json.loads(output_raw)
            else:
                output = output_raw
            expected_is_scam = output.get('is_scam', False)
            category = output.get('category', 'UNKNOWN')
            samples.append({
                'transcript': transcript,
                'expected': expected_is_scam,
                'category': category,
            })
    
    # Ensure we pick a diverse sample from across the dataset
    random.seed(42)  # reproducible
    if len(samples) > max_samples:
        samples = random.sample(samples, max_samples)
    return samples

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# Category stats tracker
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
class CategoryStats:
    def __init__(self):
        self.data = {}

    def record(self, category, expected, predicted):
        if category not in self.data:
            self.data[category] = {'total': 0, 'correct': 0, 'fp': 0, 'fn': 0, 'tp': 0, 'tn': 0}
        self.data[category]['total'] += 1
        if expected == predicted:
            self.data[category]['correct'] += 1
            if predicted:
                self.data[category]['tp'] += 1
            else:
                self.data[category]['tn'] += 1
        else:
            if predicted:
                self.data[category]['fp'] += 1
            else:
                self.data[category]['fn'] += 1

    def print_table(self):
        print(f"\n{'Category':<30} {'Total':>6} {'Acc%':>7} {'TP':>4} {'TN':>4} {'FP':>4} {'FN':>4}")
        print("???" * 65)
        for cat, s in sorted(self.data.items()):
            acc = (s['correct'] / s['total'] * 100) if s['total'] > 0 else 0
            status = "[PASS]" if acc >= 90 else ("[WARN]" if acc >= 70 else "[FAIL]")
            print(f"{status} {cat:<28} {s['total']:>6} {acc:>6.1f}% {s['tp']:>4} {s['tn']:>4} {s['fp']:>4} {s['fn']:>4}")

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# MAIN BENCHMARK
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
async def run_benchmark():
    print("=" * 65)
    print("  PhaseGuard Deep Architecture Benchmark")
    print("  Testing: Rule-Based Engine (Stage 1)")
    print("=" * 65)

    print(f"\nLoading dataset from: {DATASET_PATH}")
    samples = load_dataset(DATASET_PATH, max_samples=500)
    print(f"Loaded {len(samples)} samples")

    classifier = LocalScamClassifier()
    classifier.load_model()

    cat_stats = CategoryStats()
    total = 0
    correct = 0
    tp = tn = fp = fn = 0
    missed_scams = []
    wrong_flags = []

    print("\nRunning 500-sample deep test...\n")
    t0 = time.perf_counter()

    for s in samples:
        transcript = s['transcript']
        expected = s['expected']
        category = s['category']

        result = await classifier.predict_instant_scam(transcript)
        predicted = result.get('is_scam', False)

        total += 1
        if expected == predicted:
            correct += 1
            if predicted:
                tp += 1
            else:
                tn += 1
        else:
            if predicted:
                fp += 1
                wrong_flags.append({'category': category, 'transcript': transcript[:120]})
            else:
                fn += 1
                missed_scams.append({'category': category, 'transcript': transcript[:120]})

        cat_stats.record(category, expected, predicted)

        # Progress dots
        if total % 50 == 0:
            print(f"  Progress: {total}/500 ...")

    elapsed = time.perf_counter() - t0

    # ?????? RESULTS ??????
    accuracy = correct / total * 100
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0

    print("\n" + "=" * 65)
    print("  OVERALL RESULTS")
    print("=" * 65)
    print(f"  Total Tested       : {total}")
    print(f"  Correct            : {correct}")
    print(f"  Accuracy           : {accuracy:.2f}%")
    print(f"  Precision          : {precision:.2%}  (how precise when flagging scam)")
    print(f"  Recall             : {recall:.2%}  (how many real scams we caught)")
    print(f"  F1 Score           : {f1:.2%}  (balance of precision & recall)")
    print()
    print(f"  True Positives     : {tp}  (scams correctly caught)")
    print(f"  True Negatives     : {tn}  (legit calls correctly passed)")
    print(f"  False Positives    : {fp}  (legit calls wrongly flagged)")
    print(f"  False Negatives    : {fn}  (scams that slipped through -> go to Stage 2/3)")
    print()
    print(f"  Total Time         : {elapsed*1000:.0f}ms")
    print(f"  Avg per detection  : {elapsed/total*1000:.3f}ms")
    print(f"  Speed              : {total/elapsed:.0f} detections/sec")
    print("=" * 65)

    print("\n--- PER-CATEGORY BREAKDOWN ---")
    cat_stats.print_table()

    if missed_scams:
        print(f"\n--- SAMPLE MISSED SCAMS (FN={fn}) - Go to Stage 2/3 LLM ---")
        for m in missed_scams[:10]:
            print(f"  [{m['category']}] {m['transcript']}...")

    if wrong_flags:
        print(f"\n--- SAMPLE WRONG FLAGS (FP={fp}) ---")
        for w in wrong_flags[:5]:
            print(f"  [{w['category']}] {w['transcript']}...")

    print("\n??? Stage 1 Rule-Based Engine benchmark complete.")
    if fn > 0:
        print(f"??????  {fn} scams that bypassed rules will be handled by Stage 2 (Local LLM) or Stage 3 (Web Fact-Check).")

if __name__ == '__main__':
    asyncio.run(run_benchmark())

